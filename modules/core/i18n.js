export const LANG = /^fr\b/i.test(navigator.language || '') ? 'fr' : 'en';

export function t(key, vars = {}) {
  const template = STRINGS[LANG][key] ?? STRINGS.fr[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ''));
}

const ERROR_KEYS = {
  extension_reloaded: 'ERR_EXTENSION_RELOADED',
  not_found: 'ERR_NOT_FOUND',
  no_url: 'ERR_NO_URL',
  timeout: 'ERR_TIMEOUT',
  invalid_query: 'ERR_INVALID_QUERY',
  unknown_id: 'ERR_UNKNOWN_ID',
  capture_no_video: 'ERR_CAPTURE_NO_VIDEO',
  capture_tainted: 'ERR_CAPTURE_TAINTED'
};

export function errorMessage(error) {
  const code = error?.code || error?.message || String(error);
  if (ERROR_KEYS[code]) return t(ERROR_KEYS[code]);
  if (/^http_\d+$/.test(code)) return t('ERR_HTTP', { status: code.slice(5) });
  return t('ERR_GENERIC', { message: code });
}

const relative = new Intl.RelativeTimeFormat(LANG, { numeric: 'auto' });

export function timeAgo(seconds) {
  if (!seconds) return '';
  const diff = Math.round(seconds - Date.now() / 1000);
  const abs = Math.abs(diff);
  if (abs < 60) return relative.format(diff, 'second');
  if (abs < 3600) return relative.format(Math.round(diff / 60), 'minute');
  if (abs < 86400) return relative.format(Math.round(diff / 3600), 'hour');
  return relative.format(Math.round(diff / 86400), 'day');
}

const dateFormat = new Intl.DateTimeFormat(LANG, { day: 'numeric', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit' });

export function formatDate(seconds) {
  return seconds ? dateFormat.format(new Date(seconds * 1000)) : '';
}

export function formatDuration(seconds) {
  const total = Math.round(seconds);
  return `${Math.floor(total / 60)}:${String(total % 60).padStart(2, '0')}`;
}
